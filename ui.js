function readPreference(key) {
  try { return localStorage.getItem(key); }
  catch { return null; }
}

function writePreference(key, value) {
  try { localStorage.setItem(key, value); }
  catch { /* Keep the preference for this visit. */ }
}

const languageKey = "ocarina-language-v1";
const themeKey = "ocarina-theme-v1";
const requestedLanguage = new URLSearchParams(location.search).get("lang");
let uiLanguage = (requestedLanguage ?? readPreference(languageKey)) === "en" ? "en" : "zh-CN";

function tr(source, values) {
  const pattern = uiLanguage === "en" ? englishText[source] ?? source : source;
  return values ? pattern.replace(/\{(\w+)\}/g, (match, token) => Object.hasOwn(values, token) ? values[token] : match) : pattern;
}

function barCount(count) {
  return count === 1 ? tr("1 小节") : tr("{count} 小节", { count });
}

function beatCount(count) {
  return Number(count) === 1 ? tr("1 拍") : tr("{count} 拍", { count });
}

// Record only the text shipped in the page. Score titles and annotations are user data.
const staticPageText = [];
const textWalker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
for (let node; (node = textWalker.nextNode());) {
  const original = node.nodeValue;
  const key = original.trim();
  if (Object.hasOwn(englishText, key)) staticPageText.push(() => { node.nodeValue = original.replace(key, tr(key)); });
}
for (const element of document.querySelectorAll("[title], [aria-label], [placeholder], [alt], meta[name=description]")) {
  for (const attribute of ["title", "aria-label", "placeholder", "alt", "content"]) {
    const key = element.getAttribute(attribute);
    if (key && Object.hasOwn(englishText, key)) staticPageText.push(() => element.setAttribute(attribute, tr(key)));
  }
}

function localizePage() {
  document.documentElement.lang = uiLanguage;
  staticPageText.forEach((update) => update());
}

document.documentElement.dataset.theme = readPreference(themeKey) === "dark" ? "dark" : "light";
localizePage();
